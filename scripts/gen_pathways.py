#!/usr/bin/env python3
"""Generate the learning-pathway pages of MESA Trainings from data/pathways.yml.

Reads the pathway data together with each tutorial's front matter and its
"**Time:** ... **You need:** ..." line, and writes:

  docs/pathways/index.md      the section listing (OKF §8: no front matter)
  docs/pathways/<id>.md       one page per pathway
  docs/pathways/self-checks.md  every self-check with its answer, readable
                              without scripts
  docs/pathway.md             every tutorial under its pathway point
  docs/assets/pathways.json   the same facts for scripts in the browser

Every page is plain Markdown: ordered lists of links with the time each takes.
The files are committed; CI regenerates them and fails if they have drifted,
as it does for llms.txt. Run this before scripts/gen_llms_txt.py, which indexes
the pages written here.

Usage: python scripts/gen_pathways.py      (from the repository root)
Exit status 1, with nothing written, if the data names a tutorial that does not
exist, breaks a limit, or produces a page missing from the nav in zensical.toml.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from okf_common import DOCS, ROOT, load_config, nav_pages, split_frontmatter  # noqa: E402

DATA = ROOT / "data" / "pathways.yml"
PRODUCER = "gen-pathways/1"
MAX_IN_VIEW = 7
POINT_TAG = re.compile(r"p[1-5]")
TIME_PARA = re.compile(r"^\*\*Time:\*\*(.*?)(?:\n\s*\n|\Z)", re.S | re.M)
MINUTES = re.compile(r"\s*(\d+)(?:\s*(?:to|–|-)\s*(\d+))?\s+minutes")
YOU_WILL = re.compile(r"^\*\*You will:\*\*(.*?)(?:\n\s*\n|\Z)", re.S | re.M)
LOCAL_LINK = re.compile(r"\]\(([a-z0-9-]+)\.md(?:#[^)]*)?\)")
NOTE = ("<!-- Generated by scripts/gen_pathways.py from data/pathways.yml. "
        "Do not edit this file: change the data and run the script. -->")
DRAFTS = ('!!! warning "These tutorials are drafts"\n'
          "    Each tutorial says at the top how far it has been checked.")


class PathwayError(Exception):
    """The data and the tutorials do not agree."""


def parse_time(body: str) -> tuple[int, int] | None:
    """Minutes (least, most) from a tutorial's "**Time:**" line, or None."""
    para = TIME_PARA.search(body)
    found = MINUTES.match(para.group(1)) if para else None
    if not found:
        return None
    low = int(found.group(1))
    return low, int(found.group(2) or low)


def parse_needs(body: str, slug: str) -> list[str]:
    """Names of the tutorials linked from the "You need" part of the Time line."""
    para = TIME_PARA.search(body)
    if not para or "**You need:**" not in para.group(1):
        return []
    names = LOCAL_LINK.findall(para.group(1).split("**You need:**", 1)[1])
    return [n for n in dict.fromkeys(names) if n != slug]


def count(n: int) -> str:
    return f"{n} tutorial" if n == 1 else f"{n} tutorials"


def parse_outcome(body: str) -> str:
    """What the reader ends up with: the tutorial's "**You will:**" sentence,
    without its label, or "" if the page has none."""
    found = YOU_WILL.search(body)
    return " ".join(found.group(1).split()) if found else ""


def minutes(low: int, high: int) -> str:
    return f"{low} minutes" if low == high else f"{low} to {high} minutes"


def load_tutorials(data: dict, folder: Path | None = None) -> dict[str, dict]:
    """Facts about every page in docs/tutorials/, keyed by file name."""
    folder = folder or DOCS / "tutorials"
    tutorials, problems = {}, []
    for path in sorted(folder.glob("*.md")):
        if path.name == "index.md":
            continue
        slug = path.stem
        fm, body = split_frontmatter(path.read_text(encoding="utf-8"))
        fm = fm or {}
        points = [t for t in fm.get("tags", []) if POINT_TAG.fullmatch(str(t))]
        if len(points) != 1:
            problems.append(f"{path.name}: needs exactly one pathway tag p1 to p5, has {points}")
            continue
        time = (data.get("times") or {}).get(slug) or parse_time(body)
        if not time:
            problems.append(f"{path.name}: no '**Time:** N minutes' line, and no entry under `times`")
            continue
        tutorials[slug] = {
            "title": str(fm.get("title", slug)),
            "description": str(fm.get("description", "")),
            "outcome": parse_outcome(body),
            "point": points[0],
            "min": int(time[0]),
            "max": int(time[1]),
            "status": str(fm.get("status", "")),
            "revised": str((fm.get("generated") or {}).get("at", "")),
            "stale_after": str(fm.get("stale_after", "")),
            "builds_on": parse_needs(body, slug),
        }
    for slug, names in (data.get("builds_on") or {}).items():
        if slug not in tutorials:
            problems.append(f"builds_on: no tutorial named {slug}")
        else:
            tutorials[slug]["builds_on"] = list(names)
    for slug, facts in tutorials.items():
        facts["builds_on"] = [n for n in facts["builds_on"] if n in tutorials]
    if problems:
        raise PathwayError("\n".join(problems))
    return tutorials


def check(data: dict, tutorials: dict[str, dict]) -> list[str]:
    """Problems in the pathway data, as messages; empty when it is sound."""
    problems = []
    points = data.get("points") or {}
    ids = [p["id"] for p in data.get("pathways", [])]
    for pid in sorted({i for i in ids if ids.count(i) > 1}):
        problems.append(f"pathway id {pid} is used more than once")
    for pathway in data.get("pathways", []):
        where, seen = f"pathway {pathway['id']}", set()
        if pathway.get("after") and pathway["after"] not in ids:
            problems.append(f"{where}: `after` names no pathway: {pathway['after']}")
        for stage in pathway["stages"]:
            stage.setdefault("tutorials", [])
            if stage["point"] not in points:
                problems.append(f"{where}: unknown point {stage['point']}")
            if not stage["tutorials"] and not stage.get("more"):
                problems.append(f"{where}, {stage['point']}: the stage is empty")
            if len(stage["tutorials"]) > MAX_IN_VIEW:
                problems.append(f"{where}, {stage['point']}: {len(stage['tutorials'])} tutorials in "
                                f"view; the limit is {MAX_IN_VIEW}. Move some under `more`.")
            for slug in stage["tutorials"] + stage.get("more", []):
                if slug not in tutorials:
                    problems.append(f"{where}: no tutorial named {slug}")
                elif tutorials[slug]["point"] != stage["point"]:
                    problems.append(f"{where}: {slug} is tagged {tutorials[slug]['point']} "
                                    f"but listed under {stage['point']}")
                if slug in seen:
                    problems.append(f"{where}: {slug} is listed twice")
                seen.add(slug)
        limit = data.get("essentials_minutes")
        named = [s for s in core(pathway) if s in tutorials]
        if not named:
            problems.append(f"{where}: no essentials; put at least one tutorial under `tutorials:`")
        elif limit and total(named, tutorials)[1] > limit:
            problems.append(f"{where}: the essentials take up to {total(named, tutorials)[1]} minutes; "
                            f"the limit is {limit}. Move some under `more`.")
    tailoring = data.get("tailoring") or {}
    for slug in tailoring.get("foundations") or []:
        if slug not in tutorials:
            problems.append(f"tailoring.foundations: no tutorial named {slug}")
    for slug, instead in (tailoring.get("in_r") or {}).items():
        for name in (slug, instead):
            if name is not None and name not in tutorials:
                problems.append(f"tailoring.in_r: no tutorial named {name}")
    checks = data.get("checks") or {}
    for cid, c in checks.items():
        where = f"check {cid}"
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", str(cid)):
            problems.append(f"{where}: the name must be lower case with hyphens")
        for key in ("tutorial", "ask", "answer", "right", "otherwise"):
            if c.get(key) in (None, ""):
                problems.append(f"{where}: `{key}` is missing")
        if c.get("tutorial") not in tutorials:
            problems.append(f"{where}: no tutorial named {c.get('tutorial')}")
        if "options" in c:
            if answer_text(c) not in [str(o) for o in c["options"]]:
                problems.append(f"{where}: the answer is not among the options")
        elif not isinstance(c.get("answer"), (int, float)) or isinstance(c.get("answer"), bool):
            problems.append(f"{where}: without `options`, the answer must be a number")
        for slip in (c.get("slips") or {}):
            if str(slip) == answer_text(c):
                problems.append(f"{where}: a slip repeats the answer")
            if "options" in c and str(slip) not in [str(o) for o in c["options"]]:
                problems.append(f"{where}: slip {slip!r} is not among the options")
        if set(c.get("verify") or {}) - {"python", "r"}:
            problems.append(f"{where}: `verify` takes `python` or `r`")
    for key, point in points.items():
        for cid in point.get("skip_check") or []:
            if cid not in checks:
                problems.append(f"point {key}: skip_check names no self-check: {cid}")
            elif checks[cid].get("tutorial") in tutorials and tutorials[checks[cid]["tutorial"]]["point"] != key:
                problems.append(f"point {key}: skip_check {cid} belongs to another point")
    placed = set()
    for point, groups in (data.get("by_point") or {}).items():
        for group in groups:
            if len(group["tutorials"]) > MAX_IN_VIEW:
                problems.append(f"by_point {point}: a group of {len(group['tutorials'])}; "
                                f"the limit is {MAX_IN_VIEW}")
            for slug in group["tutorials"]:
                if slug not in tutorials:
                    problems.append(f"by_point {point}: no tutorial named {slug}")
                elif tutorials[slug]["point"] != point:
                    problems.append(f"by_point {point}: {slug} is tagged {tutorials[slug]['point']}")
                if slug in placed:
                    problems.append(f"by_point: {slug} is listed twice")
                placed.add(slug)
    return problems


def by_point(data: dict, tutorials: dict[str, dict]) -> tuple[dict[str, list[dict]], list[str]]:
    """The groups under each point, with any tutorial the data leaves out
    added to the end of its point. Returns (groups, names that were added)."""
    groups = {p: [{"title": g.get("title", ""), "tutorials": list(g["tutorials"])}
                  for g in (data.get("by_point") or {}).get(p, [])] for p in data["points"]}
    placed = {s for gs in groups.values() for g in gs for s in g["tutorials"]}
    added = [s for s in tutorials if s not in placed]
    for slug in added:
        point_groups = groups[tutorials[slug]["point"]]
        if point_groups and point_groups[-1]["title"] == "More" \
                and len(point_groups[-1]["tutorials"]) < MAX_IN_VIEW:
            point_groups[-1]["tutorials"].append(slug)
        else:
            point_groups.append({"title": "More" if point_groups else "", "tutorials": [slug]})
    return groups, added


def total(slugs: list[str], tutorials: dict[str, dict]) -> tuple[int, int]:
    return (sum(tutorials[s]["min"] for s in slugs), sum(tutorials[s]["max"] for s in slugs))


def core(pathway: dict) -> list[str]:
    """The tutorials of a pathway, in order, without those under `more`."""
    return [s for stage in pathway["stages"] for s in stage.get("tutorials", [])]


def item(slug: str, tutorials: dict[str, dict], prefix: str) -> str:
    facts = tutorials[slug]
    return f"[{facts['title']}]({prefix}{slug}.md) ({minutes(facts['min'], facts['max'])})"


def ability(point: dict) -> str:
    """The point's competency and what it means; the name is left out where it
    only repeats the point's title."""
    if point["competency"] == point["title"]:
        return point["can_do"]
    return f"*{point['competency']}.* {point['can_do']}"


def answer_text(c: dict) -> str:
    """A self-check's answer as the reader would write it, without its unit."""
    answer = c.get("answer")
    if isinstance(answer, float) and answer.is_integer():
        answer = int(answer)
    return str(answer)


def plain(text: str) -> str:
    return " ".join(str(text).split())


CHECKS_TITLE = "Self-checks"
CHECKS_DESCRIPTION = ("Short questions for checking yourself after a tutorial, each with its answer, "
                      "the likely slips, and how the answer is confirmed against the practice data.")


def checks_page(data: dict, tutorials: dict[str, dict], source: tuple) -> str:
    checks = data.get("checks") or {}
    slugs = sorted({c["tutorial"] for c in checks.values()})
    lines = front_matter("Reference", CHECKS_TITLE, CHECKS_DESCRIPTION,
                         ["pathway", "self-check", "practice-data"], data["revised"],
                         earliest_stale(slugs, tutorials), [source])
    lines += [f"# {CHECKS_TITLE}", "", NOTE, "",
              "A self-check is one short question to try after a tutorial. Its answer comes from "
              "doing the task: most ask for a number the tutorial does not print, which you get "
              "with a small change to what it taught. They are for your own use. Nothing records "
              "or sends your answers unless you use the check on the tutorial's own page, and "
              "then only [in your own browser](../progress.md).", "",
              "Each answer is folded away. Try the question first.", ""]
    for number, (key, point) in enumerate(data["points"].items(), 1):
        mine = [(cid, c) for cid, c in checks.items() if tutorials[c["tutorial"]]["point"] == key]
        if not mine:
            continue
        lines += [f"## {number}. {point['title']}", ""]
        skip = point.get("skip_check") or []
        if skip:
            lines += [f"Already at home here? If you can answer the {len(skip)} questions marked "
                      "*skip-check*, you can skip this point. If one goes wrong, its tutorial "
                      "covers it.", ""]
        for cid, c in mine:
            title = plain(c["ask"]).replace("`", "").replace('"', "'")
            answer = answer_text(c) + (f" {c['unit']}" if c.get("unit") else "")
            lines += [f'??? question "{title}"',
                      f"    After [{tutorials[c['tutorial']]['title']}](../tutorials/{c['tutorial']}.md)"
                      + (" · *skip-check*" if cid in skip else "") + ".", ""]
            if "`" in c["ask"]:
                lines += [f"    {plain(c['ask'])}", ""]
            if "options" in c:
                lines += [f"    - {o}" for o in c["options"]] + [""]
            lines += ['    ??? success "Answer"', f"        **{answer}.** {plain(c['right'])}", ""]
            how = c.get("how") or ""
            if how:
                lines += ["        ```" + ("r" if "r" in (c.get("verify") or {}) else "python"),
                          f"        {how}", "        ```", ""]
            for slip, why in (c.get("slips") or {}).items():
                lines += [f"        If you answered *{slip}*: {plain(why)}", ""]
            lines += ["        " + ("Confirmed against the practice data each time this site is built."
                                    if c.get("verify") else
                                    "Not machine-checked: this is about a portal screen, which only a "
                                    "person can confirm."), ""]
    lines += ["## Next", "", "- [Choose a pathway](index.md)", "- [Your progress](../progress.md)"]
    return "\n".join(lines) + "\n"


def numbered(slugs: list[str], tutorials: dict[str, dict], prefix: str) -> list[str]:
    return [f"{n}. {item(s, tutorials, prefix)}" for n, s in enumerate(slugs, 1)]


def front_matter(kind: str, title: str, description: str, tags: list[str], at: str,
                 stale_after: str, sources: list[tuple[str, str, str]]) -> list[str]:
    lines = ["---", f"type: {kind}", f"title: {json.dumps(title, ensure_ascii=False)}",
             f"description: {json.dumps(description, ensure_ascii=False)}",
             f"tags: [{', '.join(tags)}]", "status: draft",
             f'generated: {{ by: "{PRODUCER}", at: "{at}T00:00:00Z" }}']
    if stale_after:
        lines.append(f'stale_after: "{stale_after}"')
    lines.append("sources:")
    for source_id, resource, source_title in sources:
        lines += [f"  - id: {source_id}", f'    resource: "{resource}"',
                  f'    title: "{source_title}"', '    author: "team:idss-mesa"']
    return lines + ["---", ""]


def describe(pathway: dict, tutorials: dict[str, dict]) -> str:
    slugs = core(pathway)
    return (f"{pathway['promise'].rstrip('.')}: {count(len(slugs))} to start with, "
            f"{minutes(*total(slugs, tutorials))} in all, and more for when you have time.")


def earliest_stale(slugs: list[str], tutorials: dict[str, dict]) -> str:
    dates = [tutorials[s]["stale_after"] for s in slugs if tutorials[s]["stale_after"]]
    return min(dates) if dates else ""


def pathway_page(pathway: dict, data: dict, tutorials: dict[str, dict], source: tuple) -> str:
    slugs = core(pathway)
    everything = slugs + [s for stage in pathway["stages"] for s in stage.get("more", [])]
    titles = {p["id"]: p["title"] for p in data["pathways"]}
    lines = front_matter("Guide", pathway["title"], describe(pathway, tutorials),
                         ["pathway", pathway["id"]], data["revised"],
                         earliest_stale(everything, tutorials), [source])
    lines += [f"# {pathway['title']}", "", NOTE, "", pathway["promise"], "",
              f"**The essentials: {count(len(slugs))}, {minutes(*total(slugs, tutorials))} in all.** "
              "Take them in order, or start wherever your question is. Nothing is locked. "
              "Each point also lists what to take if you have more time.", ""]
    if pathway.get("note"):
        lines += [plain(pathway["note"]), ""]
    if pathway.get("after"):
        lines += [f"New to the portal? Take [{titles[pathway['after']]}]({pathway['after']}.md) "
                  "first.", ""]
    lines += [DRAFTS, ""]
    for stage in pathway["stages"]:
        point = data["points"][stage["point"]]
        lines += [f"## {point['title']}", "", ability(point), ""]
        if stage["tutorials"]:
            lines += numbered(stage["tutorials"], tutorials, "../tutorials/") + [""]
        if stage.get("more"):
            lines += ["If you have more time:", ""]
            lines += [f"- {item(s, tutorials, '../tutorials/')}" for s in stage["more"]] + [""]
    lines += ["## Next", "",
              "- [Choose another pathway](index.md)",
              "- [Every tutorial, by pathway point](../pathway.md)"]
    return "\n".join(lines) + "\n"


POINT_PAGE_TITLE = "Every tutorial, by pathway point"
POINT_PAGE_DESCRIPTION = ("Every MESA tutorial under the five points of the learning pathway, from "
                          "finding your way around to sharing work others can rerun, with the time "
                          "each takes.")


def point_page(data: dict, tutorials: dict[str, dict], groups: dict, source: tuple) -> str:
    docs = ("docs", "https://idss-mesa.github.io/docs/", "MESA documentation")
    lines = front_matter("Reference", POINT_PAGE_TITLE, POINT_PAGE_DESCRIPTION,
                         ["pathway", "tutorials", "getting-started"], data["revised"],
                         earliest_stale(list(tutorials), tutorials), [source, docs])
    lines += [f"# {POINT_PAGE_TITLE}", "", NOTE, "",
              "The tutorials build five abilities, one at each point of the MESA learning "
              "pathway. Each point builds on the one before, but every tutorial says what it "
              "needs, so you can start wherever your question is.", "",
              "This page lists them all. If you have a goal in mind, a pathway is a shorter "
              "route:", ""]
    for pathway in data["pathways"]:
        slugs = core(pathway)
        lines.append(f"- [{pathway['title']}](pathways/{pathway['id']}.md): {count(len(slugs))}, "
                     f"{minutes(*total(slugs, tutorials))}")
    lines += ["", DRAFTS, ""]
    for number, (key, point) in enumerate(data["points"].items(), 1):
        slugs = [s for g in groups[key] for s in g["tutorials"]]
        lines += [f"## {number}. {point['title']}", "",
                  f"{ability(point)} "
                  f"{count(len(slugs))}, {minutes(*total(slugs, tutorials))} in all.", ""]
        for group in groups[key]:
            if group["title"]:
                lines += [f"### {group['title']}", ""]
            lines += numbered(group["tutorials"], tutorials, "tutorials/") + [""]
    lines += ["## Looking for one thing?", "",
              "Every tutorial is listed, with a one-line description, under "
              "[Tutorials](tutorials/index.md)."]
    return "\n".join(lines) + "\n"


def index_page(data: dict, tutorials: dict[str, dict]) -> str:
    lines = ["# Learning pathways", ""]
    lines += [f"* [{p['title']}]({p['id']}.md) - {describe(p, tutorials)}" for p in data["pathways"]]
    lines.append(f"* [{POINT_PAGE_TITLE}](../pathway.md) - {POINT_PAGE_DESCRIPTION}")
    if data.get("checks"):
        lines.append(f"* [{CHECKS_TITLE}](self-checks.md) - {CHECKS_DESCRIPTION}")
    for rel in data.get("also_list") or []:
        fm, _ = split_frontmatter((DOCS / rel).read_text(encoding="utf-8"))
        lines.append(f"* [{fm['title']}](../{rel}) - {fm['description']}")
    return "\n".join(lines) + "\n"


def manifest(data: dict, tutorials: dict[str, dict], groups: dict) -> str:
    pathways = []
    for pathway in data["pathways"]:
        low, high = total(core(pathway), tutorials)
        pathways.append({
            "id": pathway["id"], "title": pathway["title"], "promise": pathway["promise"],
            "after": pathway.get("after", ""), "note": plain(pathway.get("note", "")), "min": low, "max": high,
            "stages": [{"point": s["point"], "tutorials": s["tutorials"], "more": s.get("more", [])}
                       for s in pathway["stages"]],
        })
    out = {
        "schema": data["schema"],
        "revised": data["revised"],
        "points": {k: {"title": p["title"], "competency": p["competency"], "can_do": p["can_do"],
                       "reflection": p.get("reflection", ""), "skip_check": p.get("skip_check") or []}
                   for k, p in data["points"].items()},
        "checks": {cid: {"tutorial": c["tutorial"], "ask": plain(c["ask"]), "answer": answer_text(c),
                         "options": [str(o) for o in c.get("options", [])], "unit": c.get("unit", ""),
                         "how": c.get("how", ""), "right": plain(c["right"]),
                         "slips": {str(k): plain(v) for k, v in (c.get("slips") or {}).items()},
                         "otherwise": plain(c["otherwise"]), "verify": c.get("verify") or {}}
                   for cid, c in (data.get("checks") or {}).items()},
        "pathways": pathways,
        "tailoring": {"foundations": list((data.get("tailoring") or {}).get("foundations") or []),
                      "in_r": dict((data.get("tailoring") or {}).get("in_r") or {})},
        "by_point": groups,
        "tutorials": tutorials,
    }
    return json.dumps(out, indent=1, ensure_ascii=False) + "\n"


def build(data: dict, tutorials: dict[str, dict], repo_url: str = "") -> tuple[dict[str, str], list[str]]:
    """Every generated file as {path under docs/: content}, and the tutorials
    that by_point left out. Raises PathwayError if the data is unsound."""
    problems = check(data, tutorials)
    if problems:
        raise PathwayError("\n".join(problems))
    groups, added = by_point(data, tutorials)
    source = ("pathways", f"{repo_url.rstrip('/')}/blob/main/data/pathways.yml",
              "MESA Trainings pathway data")
    files = {f"pathways/{p['id']}.md": pathway_page(p, data, tutorials, source)
             for p in data["pathways"]}
    if data.get("checks"):
        files["pathways/self-checks.md"] = checks_page(data, tutorials, source)
    files["pathways/index.md"] = index_page(data, tutorials)
    files["pathway.md"] = point_page(data, tutorials, groups, source)
    files["assets/pathways.json"] = manifest(data, tutorials, groups)
    return files, added


def missing_from_nav(files: dict[str, str], nav: list) -> list[str]:
    listed = {target for _, _, target in nav_pages(nav)}
    return sorted(rel for rel in files if rel.endswith(".md") and rel not in listed)


def main() -> int:
    data = yaml.safe_load(DATA.read_text(encoding="utf-8"))
    cfg = load_config()
    try:
        tutorials = load_tutorials(data)
        files, added = build(data, tutorials, cfg.get("repo_url", ""))
    except PathwayError as err:
        print(f"error: {DATA.relative_to(ROOT)} and the tutorials do not agree:\n{err}",
              file=sys.stderr)
        return 1
    missing = missing_from_nav(files, cfg.get("nav", []))
    if missing:
        print("error: add these pages to the nav in zensical.toml:\n  " + "\n  ".join(missing),
              file=sys.stderr)
        return 1
    folder = DOCS / "pathways"
    folder.mkdir(exist_ok=True)
    for stale in folder.glob("*.md"):
        if f"pathways/{stale.name}" not in files:
            stale.unlink()
    for rel, content in files.items():
        (DOCS / rel).write_text(content, encoding="utf-8")
    for slug in added:
        print(f"note: {slug} is not under `by_point`; added to the end of {tutorials[slug]['point']}")
    print(f"pathways: {len(data['pathways'])} pathway pages, {len(tutorials)} tutorials, "
          f"{len(files)} files written")
    return 0


